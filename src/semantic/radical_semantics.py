def sememe_of_char(ch: str) -> int | None:
    """字符所属部首的义素编号（0~213）；无部首返回 None。"""
    from src.tokenizer.radicals import char_radical_num
    rn = char_radical_num(ch)
    return (rn - 1) if rn is not None and 1 <= rn <= 214 else None
