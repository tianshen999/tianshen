def radical_meaning_table() -> dict[str, dict]:
    """部首字（U+2F00 区）→ {meaning, status, index}。"""
    out: dict[str, dict] = {}
    for idx, meaning, status in _MEANINGS:
        ch = KANGXI_RADICALS[idx - 1]
        out[ch] = {"meaning": meaning, "status": status, "index": idx}
    return out


